    private void reservationTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_reservationTableMouseClicked
        int selectedRow = reservationTable.getSelectedRow();

    if (selectedRow >= 0) {
        // Extract values from the selected row
        String refId = reservationTable.getValueAt(selectedRow, 0).toString();
        String customerId = reservationTable.getValueAt(selectedRow, 1).toString();
        String from = reservationTable.getValueAt(selectedRow, 2).toString();
        String to = reservationTable.getValueAt(selectedRow, 3).toString();
        String departureDate = reservationTable.getValueAt(selectedRow, 4).toString();
        String classType = reservationTable.getValueAt(selectedRow, 5).toString();
        String flightId = reservationTable.getValueAt(selectedRow, 6).toString();
        String totalPrice = reservationTable.getValueAt(selectedRow, 7).toString();

        // Set them to input fields
        refIdInput.setText(refId);
        cusIdInput.setText(customerId);
        fromInput.setText(from);
        toInput.setText(to);
        depDateInput.setText(departureDate);
        classInput.setText(classType);
        flightIdInput.setText(flightId);
        totalPriceInput.setText(totalPrice);
    }
    }//GEN-LAST:event_reservationTableMouseClicked

