    public void populateFormFromTable() {
        int row = reservationTable.getSelectedRow();
        if (row >= 0) {
            refIdInput.setText(reservationTable.getValueAt(row, 0).toString());
            cusIdInput.setText(reservationTable.getValueAt(row, 1).toString());
            fromInput.setText(reservationTable.getValueAt(row, 2).toString());
            toInput.setText(reservationTable.getValueAt(row, 3).toString());
            depDateInput.setText(reservationTable.getValueAt(row, 4).toString());
            classInput.setText(reservationTable.getValueAt(row, 5).toString());
            flightIdInput.setText(reservationTable.getValueAt(row, 6).toString());
            totalPriceInput.setText(reservationTable.getValueAt(row, 7).toString());
        }
    }
