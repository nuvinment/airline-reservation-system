    public reservationMgmtModel getReservationFromForm() {
        return new reservationMgmtModel(
            refIdInput.getText(),
            cusIdInput.getText(),
            fromInput.getText(),
            toInput.getText(),
            java.time.LocalDate.parse(depDateInput.getText()),
            classInput.getText(),
            flightIdInput.getText(),
            Double.parseDouble(totalPriceInput.getText())
        );
    }
    

   

    public void displayReservations(List<reservationMgmtModel> reservations) {
        DefaultTableModel model = (DefaultTableModel) reservationTable.getModel(); // Use table model
        model.setRowCount(0); // Clear existing rows

        for (reservationMgmtModel r : reservations) {
        model.addRow(new Object[]{
            r.getReferenceCode(),
            r.getCustomerId(),
            r.getFrom(),
            r.getTo(),
            r.getDepartureDate().toString(),
            r.getClassType(),
            r.getFlightId(),
            r.getTotalPrice()
        });
    }
}

    
   

    
