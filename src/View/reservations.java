public void displayReservations(List<reservation> reservationsList) {
    DefaultTableModel model = (DefaultTableModel) reservationTable.getModel();
    model.setRowCount(0); // Clear existing data

    for (reservation r : reservationsList) {
        model.addRow(new Object[] {
            r.getReservationId(),
            r.getCustomerId(),
            r.getFromLocation(),
            r.getToLocation(),
            r.getDepartureDate(),
            r.getFlightClass(),
            r.getFlightId(),
            r.getTotalPrice()
        });
    }
}

