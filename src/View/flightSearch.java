    // Set table data method
    public void setFlightTableData(List<flightSearchModel> flights) {
        DefaultTableModel model = (DefaultTableModel) flightTable.getModel();
        model.setRowCount(0); // clear previous data

        for (Model.flightSearchModel flight : flights) {
            model.addRow(new Object[]{
                flight.getFlightId(),
                flight.getFlightName(),
                flight.getAirlineName(),
                flight.getEconomicPrice(),
                flight.getBusinessPrice(),
                flight.getFromLocation(),
                flight.getToLocation(),
                flight.getDepartureDate(),
                flight.getReturnDate(),
                flight.getDepartureTime(),
                flight.getArrivalTime()
            });
        }
    }
    
