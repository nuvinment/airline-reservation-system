    private void populateFieldsFromTable(int rowIndex) {
        DefaultTableModel model = (DefaultTableModel) employeeTable.getModel();
        empIdInput.setText(model.getValueAt(rowIndex, 0).toString());
        empNameInput.setText(model.getValueAt(rowIndex, 1).toString());
        empEmailInput.setText(model.getValueAt(rowIndex, 2).toString());
        empPhoneInput.setText(model.getValueAt(rowIndex, 3).toString());
        empAddressInput.setText(model.getValueAt(rowIndex, 4).toString());
        empUsernameInput.setText(model.getValueAt(rowIndex, 5).toString());
        employeeCreatePwdInput.setText(model.getValueAt(rowIndex, 6).toString());
        employeeConfirmPwdInput.setText(model.getValueAt(rowIndex, 6).toString());
        
    }
    
     // Table methods
    public void setEmployeeTableData(List<Employee> employees) {
        DefaultTableModel model = (DefaultTableModel) employeeTable.getModel();
        model.setRowCount(0); // Clear existing data
        for (Employee employee : employees) {
            model.addRow(new Object[]{
                employee.getEmployeeId(),
                employee.geteName(),
                employee.geteEmail(),
                employee.getePhoneNumber(),
                employee.geteAddress(),
                employee.geteUsername(),
                employee.getePassword()
            });
        }
    }
    
    public void updateEmployeeTable(List<Employee> employees) {
        setEmployeeTableData(employees);
    }
    
