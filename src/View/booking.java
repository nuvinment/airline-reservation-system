        private void populateBookingDetails() {
        // Set the text fields with booking details
        passengerName.setText(bookingModel.getPassengerName());
        // Corrected: Convert int to String for passengerId
        passengerId.setText(String.valueOf(bookingModel.getCustomerId()));
        fromLocationn.setText(bookingModel.getFromLocation());
        toLocation.setText(bookingModel.getToLocation());
        fClass.setText(bookingModel.getFlightClass());
        flightName.setText(bookingModel.getFlightName());
        flightDate.setText(bookingModel.getFlightDate());
        depTime.setText(bookingModel.getDepartureTime());
        flightId.setText(bookingModel.getFlightId());
        passengerCount.setText(String.valueOf(bookingModel.getPassengerCount()));
        totalPrice.setText(String.format("%.2f", bookingModel.getTotalPrice())); // Format price to 2 decimal places
    }

private void updateBillContent() {
        StringBuilder billContent = new StringBuilder();
        billContent.append("=========== Booking Details ===========\n");
        // Display Reservation ID if available
        if (currentReservationId != -1) {
            billContent.append("Reservation ID    : ").append(currentReservationId).append("\n");
        }
        billContent.append("Passenger         : ").append(bookingModel.getPassengerName()).append("\n");
        billContent.append("From              : ").append(bookingModel.getFromLocation()).append("\n");
        billContent.append("To                : ").append(bookingModel.getToLocation()).append("\n");
        billContent.append("Flight Class      : ").append(bookingModel.getFlightClass()).append("\n");
        billContent.append("Flight Name       : ").append(bookingModel.getFlightName()).append("\n");
        billContent.append("Flight Date       : ").append(bookingModel.getFlightDate()).append("\n");
        billContent.append("Departure Time    : ").append(bookingModel.getDepartureTime()).append("\n");
        billContent.append("Flight ID         : ").append(bookingModel.getFlightId()).append("\n");
        billContent.append("Passenger Count   : ").append(bookingModel.getPassengerCount()).append("\n");
        billContent.append("---------------------------------------\n");
        billContent.append("Total Price       : LKR ").append(String.format("%.2f", bookingModel.getTotalPrice())).append("\n");
        billContent.append("=======================================\n");
        billContent.append("---------HAVE A SAFE FLIGHT------------\n");
        bill.setText(billContent.toString());
    }

    public void updateBillWithReservationId(int id) {
        this.currentReservationId = id;
        updateBillContent(); // Re-generate and set the bill content
    }

  

